class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem("kisansetu_lang") || "hi"; // Hindi as default
    this.listeners = [];
  }

  setLanguage(langCode) {
    if (TRANSLATIONS[langCode]) {
      this.currentLang = langCode;
      localStorage.setItem("kisansetu_lang", langCode);
      this.applyTranslations();
      this.notifyListeners();
    }
  }

  getLanguage() {
    return this.currentLang;
  }

  t(key) {
    const langObj = TRANSLATIONS[this.currentLang] || TRANSLATIONS["en"];
    return langObj[key] || TRANSLATIONS["en"][key] || key;
  }

  subscribe(callback) {
    this.listeners.push(callback);
  }

  notifyListeners() {
    this.listeners.forEach(cb => {
      try {
        cb(this.currentLang);
      } catch (e) {
        console.error("i18n callback error:", e);
      }
    });
  }

  applyTranslations() {
    const dict = TRANSLATIONS[this.currentLang] || TRANSLATIONS["en"];
    
    // Update elements with data-i18n
    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.getAttribute("data-i18n");
      if (dict[key]) {
        if (el.tagName === "INPUT" && el.hasAttribute("placeholder")) {
          el.placeholder = dict[key];
        } else {
          el.innerHTML = dict[key];
        }
      }
    });

    // Update placeholders with data-i18n-placeholder
    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
      const key = el.getAttribute("data-i18n-placeholder");
      if (dict[key]) {
        el.placeholder = dict[key];
      }
    });

    // Update active state on language selector elements
    document.querySelectorAll(".lang-card, .lang-select-option").forEach(el => {
      const lang = el.getAttribute("data-lang");
      if (lang === this.currentLang) {
        el.classList.add("active");
      } else {
        el.classList.remove("active");
      }
    });

    // Update HTML lang attribute
    document.documentElement.lang = this.currentLang;
  }
}

// Instantiate global i18n
window.i18n = new I18nManager();
